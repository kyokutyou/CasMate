// Bounded behavior checks for the memory-only UI exploration.
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { JSDOM, VirtualConsole } from 'jsdom';

const source = readFileSync(new URL('./fragment.html', import.meta.url), 'utf8');
const errors = [];
const virtualConsole = new VirtualConsole();
virtualConsole.on('jsdomError', error => errors.push(error));
const dom = new JSDOM(source, { runScripts: 'dangerously', url: 'http://localhost/?variant=A', virtualConsole });
const document = dom.window.document;
const get = selector => { const element = document.querySelector(selector); assert.ok(element, selector); return element; };
const click = selector => get(selector).click();
const state = () => JSON.parse(get('#sr-payload').textContent);
const wait = milliseconds => new Promise(resolve => setTimeout(resolve, milliseconds));
const input = (selector, value, event = 'input') => {
  get(selector).value = value;
  get(selector).dispatchEvent(new dom.window.Event(event, { bubbles: true }));
};
const variant = value => click(`[data-variant="${value}"]`);

assert.equal(state().enabled, false);
assert.equal(state().preview, false);
assert.equal(state().wav, false);
assert.equal(state().sessionRunning, false);
for (const key of ['A', 'B', 'C']) {
  variant(key);
  assert.equal(state().variant, key);
  const ids = [...document.querySelectorAll('[id]')].map(element => element.id);
  assert.equal(new Set(ids).size, ids.length, `unique IDs in ${key}`);
  assert.equal(get('h1').textContent, '配信者音声認識');
  assert.equal(get('.sr-back').textContent, '←');
  assert.equal(get('.sr-back').getAttribute('aria-label'), '設定に戻る');
  assert.equal(get('.sr-back').getAttribute('data-tooltip'), '設定に戻る');
  assert.equal(get('.sr-back').parentElement, get('h1').parentElement);
  assert.ok(get('.sr-intro strong').textContent.includes('このPC内'));
  assert.ok(get('.sr-intro p').textContent.includes('音声認識プレビュー'));
  assert.equal(get('.sr-intro-mark').getAttribute('aria-hidden'), 'true');
  assert.equal(get('.sr-editor-heading').querySelector('[role="status"]'), null);
}
input('#sr-silence', '0.8');
assert.equal(state().draft.silence, 0.8);
assert.equal(state().applied.silence, 0.5);
variant('A');
assert.equal(get('#sr-silence').value, '0.8');
click('[data-page="home"]');
click('[data-action="open-editor"]');
assert.equal(state().draft.silence, 0.8);
assert.equal(get('.sr-back').textContent, '←');
assert.equal(get('.sr-back').getAttribute('aria-label'), 'ホームに戻る');
click('[data-action="preview"]');
assert.equal(state().preview, true);
assert.equal(state().enabled, false);
assert.equal(state().sessionRunning, true);
click('#sr-sample');
assert.equal(state().history.length, 1);
click('#sr-wav');
assert.equal(state().wav, true);
click('#sr-enabled');
click('[data-action="preview"]');
assert.equal(state().enabled, true);
assert.equal(state().sessionRunning, true);
assert.equal(state().history.length, 0);
assert.equal(state().wav, false);
click('[data-action="preview"]');
assert.equal(state().wav, false);
click('#sr-enabled');
assert.equal(state().sessionRunning, true, 'preview keeps shared session running');
click('[data-action="apply"]');
assert.equal(state().busy, true);
await wait(500);
assert.equal(state().busy, false);
assert.equal(state().applied.silence, 0.8);
assert.equal(state().preview, true);
input('#sr-maximum', '0.1');
click('[data-action="apply"]');
assert.ok(state().errors.maximum);
assert.equal(state().applied.maximum, 30);
input('#sr-maximum', '30');
input('#sr-vad', '');
assert.ok(state().errors.vad);
input('#sr-vad', '0.4');
input('#sr-scenario', 'save-error', 'change');
click('[data-action="apply"]');
await wait(500);
assert.equal(state().applied.vad, 0.3);
assert.equal(state().draft.vad, 0.4);
assert.equal(get('#sr-warning-count').textContent, '1');
input('#sr-scenario', 'ready', 'change');
click('[data-action="apply"]');
await wait(500);
assert.equal(state().applied.vad, 0.4);
for (let i = 0; i < 52; i++) click('#sr-sample');
assert.equal(state().history.length, 50);
click('[data-action="preview"]');
assert.equal(state().history.length, 0);
assert.equal(state().sessionRunning, false);
variant('B');
click('[data-step="1"]');
assert.ok(get('[data-action="preview"]'));
click('[data-step="2"]');
assert.ok(get('#sr-enabled'));
click('[data-step="0"]');
input('#sr-scenario', 'missing', 'change');
assert.equal(state().model, 'missing');
click('[data-action="model"]');
assert.equal(state().model, 'downloading');
await wait(1000);
assert.equal(state().model, 'ready');
input('#sr-scenario', 'microphone', 'change');
assert.equal(get('#sr-warning-count').textContent, '1');
input('#sr-scenario', 'failed', 'change');
assert.equal(state().model, 'failed');
assert.deepEqual(errors, []);
assert.doesNotMatch(source, /\b(fetch|XMLHttpRequest|WebSocket|getUserMedia|localStorage)\s*\(/);
console.log('PASS: 3 layouts, draft/apply separation, navigation retention, preview isolation, shared session, WAV reset, 50-result cap, validation, save failure, model preparation.');
dom.window.close();
