// Focused interaction checks for the requested visual comparison.
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { JSDOM, VirtualConsole } from 'jsdom';

const errors = [];
const virtualConsole = new VirtualConsole();
virtualConsole.on('jsdomError', error => errors.push(error));
const dom = new JSDOM(readFileSync(new URL('./fragment.html', import.meta.url), 'utf8'), {
  runScripts: 'dangerously', url: 'http://localhost/?variant=A', virtualConsole,
});
const doc = dom.window.document;
const get = selector => { const el = doc.querySelector(selector); assert.ok(el, selector); return el; };
const click = selector => get(selector).click();
const state = () => JSON.parse(get('#cl-payload').textContent);
const input = (selector, value) => { const el = get(selector); el.value = value; el.dispatchEvent(new dom.window.Event('input', { bubbles: true })); };

assert.equal(state().variant, 'A');
assert.equal(doc.querySelectorAll('.cl-intro').length, 1);
assert.equal(get('.cl-back').textContent, '←');
assert.equal(get('.cl-back').getAttribute('aria-label'), '設定に戻る');
input('#cl-fontSizePx', '24');
input('#cl-textColor', '#ffccaa80');
click('#cl-showSource');
for (const variant of ['B', 'C', 'A']) {
  click(`[data-variant="${variant}"]`);
  assert.equal(state().variant, variant);
  assert.equal(state().settings.fontSizePx, 24);
  assert.equal(state().settings.textColor, '#ffccaa80');
  assert.equal(state().settings.showSource, false);
  const ids = [...doc.querySelectorAll('[id]')].map(el => el.id);
  assert.equal(new Set(ids).size, ids.length);
}
click('#cl-showAuthor');
click('#cl-showContent');
assert.equal(state().settings.showContent, true, 'Cannot hide all fields');
assert.ok(state().errors.fields);
click('#cl-showAuthor');
assert.equal(state().errors.fields, undefined);
click('[data-direction="newestTop"]');
assert.match(get('.cl-preview-stage .cl-comment').textContent, /名無しさん/);
input('#cl-fontSizePx', '201');
assert.equal(state().settings.fontSizePx, 24);
assert.equal(get('#cl-fontSizePx').getAttribute('aria-invalid'), 'true');
click('[data-variant="B"]');
assert.equal(get('#cl-fontSizePx').value, '201', 'Keep invalid input across variants');
assert.match(get('#cl-size-help').textContent, /整数/);
input('#cl-fontSizePx', '200');
assert.equal(state().settings.fontSizePx, 200);
input('#cl-fontSizePx', '8');
assert.equal(state().settings.fontSizePx, 8);
input('#cl-fontSizePx', '16');
input('#cl-textColor', 'red');
assert.equal(state().settings.textColor, '#ffccaa80');
input('[data-color="textColor"]', '#112233');
assert.equal(state().settings.textColor, '#11223380', 'RGB picker preserves alpha');
assert.equal(state().errors.textColor, undefined);
input('#cl-fontFamily', '"><img src=x onerror=alert(1)>');
click('[data-variant="A"]');
assert.equal(doc.querySelectorAll('img').length, 0, 'Font input is not HTML');
input('#cl-fontFamily', 'Yu Gothic UI');
click('[data-variant="C"]');
click('[data-tab="appearance"]');
get('#cl-fontSizePx').dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }));
assert.equal(state().variant, 'C', 'Input arrow keys do not switch variants');
get('[data-tab="appearance"]').dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }));
assert.equal(state().tab, 'window');
click('[data-action="window"]');
assert.equal(state().windowVisible, true);
click('[data-action="back"]');
assert.equal(state().page, 'settings');
assert.equal(doc.activeElement.id, 'cl-entry');
click('[data-page="home"]');
click('[data-action="editor"]');
assert.equal(get('.cl-back').getAttribute('aria-label'), 'ホームに戻る');
click('[data-action="back"]');
assert.equal(state().page, 'home');
click('[data-action="editor"]');
click('[data-variant="A"]');
const scenario = get('#cl-scenario');
scenario.value = 'save-error'; scenario.dispatchEvent(new dom.window.Event('change', { bubbles: true }));
input('#cl-fontSizePx', '30');
assert.equal(get('#cl-toast').hidden, true, 'Save failure never shows success');
assert.equal(get('#cl-warning-count').textContent, '1');
scenario.value = 'empty'; scenario.dispatchEvent(new dom.window.Event('change', { bubbles: true }));
assert.match(get('.cl-preview-stage').textContent, /コメントはまだありません/);
click('[data-action="toast"]');
assert.equal(get('#cl-toast').hidden, false);
await new Promise(resolve => setTimeout(resolve, 4100));
assert.equal(get('#cl-toast').hidden, true);
assert.deepEqual(errors, []);
dom.window.close();
console.log('PASS: 3 layouts, settings retention, validation, preview, navigation, keyboard, failure state, toast lifetime');
