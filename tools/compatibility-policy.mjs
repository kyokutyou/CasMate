import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const mode = process.argv[2];
if (!['--generate', '--check'].includes(mode) || process.argv.length !== 3) throw new Error('Usage: node tools/compatibility-policy.mjs --generate|--check');
const policy = JSON.parse(await readFile(resolve(root, 'compatibility-policy.json'), 'utf8'));
const names = ['pcSettings', 'pcSmartphoneStore', 'androidRegistrationStore', 'androidOutdoorQuality', 'privateInvitation', 'privateRegistration', 'directInvitation', 'directRegistration', 'mobileProtocol', 'controlProtocol'];
if (Object.keys(policy).sort().join() !== 'contracts,registrationContracts' || Object.keys(policy.contracts).sort().join() !== [...names].sort().join()) throw new Error('Unexpected compatibility contracts');
for (const [name, contract] of Object.entries(policy.contracts)) {
  const { current, supported, retired, initialImport } = contract;
  if (Object.keys(contract).some(key => !['current', 'supported', 'retired', 'initialImport'].includes(key)) || !Number.isSafeInteger(current) || current < 1 ||
    !Array.isArray(supported) || !Array.isArray(retired) || !supported.includes(current) ||
    [...supported, ...retired].some(version => !Number.isSafeInteger(version) || version < 1 || version > current) ||
    new Set([...supported, ...retired]).size !== supported.length + retired.length ||
    initialImport !== undefined && (name !== 'androidOutdoorQuality' || initialImport !== 'complete-unversioned')) throw new Error(`Invalid contract: ${name}`);
}
if (!Array.isArray(policy.registrationContracts) || policy.registrationContracts.length !== 2) throw new Error('Invalid registration combinations');
for (const network of ['private', 'direct']) {
  const rows = policy.registrationContracts.filter(row => row.network === network);
  if (rows.length !== 1) throw new Error(`Invalid combination: ${network}`);
  const row = rows[0];
  if (Object.keys(row).sort().join() !== 'controlProtocol,invitation,mobileProtocol,network,registration' ||
    row.invitation !== policy.contracts[`${network}Invitation`].current || row.registration !== policy.contracts[`${network}Registration`].current ||
    row.mobileProtocol !== policy.contracts.mobileProtocol.current || row.controlProtocol !== policy.contracts.controlProtocol.current) throw new Error(`Inconsistent combination: ${network}`);
}
const banner = '// Generated by pnpm compatibility:generate. Edit compatibility-policy.json.\n';
const ts = banner + `export const compatibilityPolicy = ${JSON.stringify(policy, null, 2)} as const;\n`;
const kotlinName = name => name.replace(/[A-Z]/g, letter => `_${letter}`).toUpperCase();
const kt = banner + 'package jp.casmate.app.compatibility\n\nobject CompatibilityPolicy {\n' + names.map(name => {
  const value = policy.contracts[name];
  return `    const val ${kotlinName(name)} = ${value.current}\n    val ${kotlinName(name)}_SUPPORTED = setOf(${value.supported.join(', ')})\n    val ${kotlinName(name)}_RETIRED = setOf<Int>(${value.retired.join(', ')})`;
}).join('\n') + `\n    const val IMPORT_COMPLETE_UNVERSIONED_QUALITY = ${policy.contracts.androidOutdoorQuality.initialImport === 'complete-unversioned'}\n}\n`;
for (const [path, content] of [
  ['src/shared/compatibility-policy.generated.ts', ts],
  ['android/app/src/main/java/jp/casmate/app/compatibility/CompatibilityPolicy.kt', kt],
]) {
  const target = resolve(root, path);
  if (mode === '--generate') { await mkdir(dirname(target), { recursive: true }); await writeFile(target, content, 'utf8'); }
  else if (await readFile(target, 'utf8').catch(() => '') !== content) throw new Error(`Compatibility output is stale: ${path}. Run pnpm compatibility:generate.`);
}
